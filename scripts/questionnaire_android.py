"""The questionnaire's shared Android trees: digest, generate, copy (UNIFY_2026-10-21.md, U10).

The trees below are the same Kotlin in designer-portal and documentation-portal once the package
prefix is normalised (``com.designprototype.workshop`` and ``com.fieldrepository.app`` both read as
``<pkg>``). ``questionnaire/portal/`` is NOT shared: it is each portal's own adapter (its HTTP client,
its workshops, its artisan create, its live QR reader), and the shared code reaches the portal only
through it. Edit the trees in designer-portal, then run ``scripts/sync_questionnaire.py``, which
calls :func:`sync` here; never hand-copy.

``shared/android-questionnaire.sha256`` lists every shared file with its normalised digest. It sits
outside the ``shared/questionnaire*`` glob on purpose: it is the Android twin of
``shared/questionnaire.sha256`` and is checked by the Android unit test
``questionnaire/AndroidSharedTreeTest`` (itself shared), not by the backend parity test.

Each file keeps its own line endings: digests are over LF-normalised text, and a copy writes the
target with the line endings the source has.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

PKG = {"designer-portal": "com.designprototype.workshop", "documentation-portal": "com.fieldrepository.app"}
PKG_PATH = {k: v.replace(".", "/") for k, v in PKG.items()}
TOKEN = "<pkg>"
MANIFEST = Path("shared/android-questionnaire.sha256")
#: (source set, tree) pairs that are shared. ``questionnaire/portal`` is each portal's own.
TREES = (
    ("main", "questionnaire/data"),
    ("main", "questionnaire/ui"),
    ("main", "recording"),
    ("test", "questionnaire"),
    ("test", "recording"),
    ("androidTest", "questionnaire"),
    ("androidTest", "recording"),
)
ENUMS = "questionnaire/data/QuestionnaireEnums.kt"
HEADER = "GENERATED by scripts/questionnaire_android.py from shared/enums.json, shared/questionnaire-enums.json and shared/languages.json. Do not edit; edit shared/ and run scripts/sync_questionnaire.py."


def portal_of(root: Path) -> str:
    return "designer-portal" if (root / "android/app/src/main/java" / PKG_PATH["designer-portal"]).is_dir() else "documentation-portal"


def _base(root: Path, source_set: str) -> Path:
    return root / "android/app/src" / source_set / "java" / PKG_PATH[portal_of(root)]


def shared_files(root: Path) -> list[tuple[str, Path]]:
    """``(rel, absolute)`` for every shared file; ``rel`` is ``<source set>/<tree path>``."""
    out: list[tuple[str, Path]] = []
    for source_set, tree in TREES:
        base = _base(root, source_set)
        folder = base / tree
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("*.kt")):
            rel = path.relative_to(base).as_posix()
            if rel.startswith("questionnaire/portal/"):
                continue
            out.append((f"{source_set}/{rel}", path))
    return out


def normalise(text: str) -> str:
    text = text.replace("\r\n", "\n")
    for pkg in PKG.values():
        text = text.replace(pkg, TOKEN)
    return text


def digest(path: Path) -> str:
    return hashlib.sha256(normalise(path.read_text(encoding="utf-8")).encode("utf-8")).hexdigest()


def manifest_text(root: Path) -> str:
    return "".join(f"{digest(path)}  {rel}\n" for rel, path in shared_files(root))


def _kotlin_name(value: str) -> str:
    if re.match(r"^[A-Z][A-Z0-9_]*$", value):
        return value
    return re.sub(r"(?<!^)(?=[A-Z])", "_", value).upper().replace("-", "_")


def enums_text(root: Path, portal: str) -> str:
    """The Kotlin enums: every list of ``shared/enums.json``, then the unification's own lists
    (``shared/questionnaire-enums.json``) that the first file does not already carry."""
    enums = json.loads((root / "shared/enums.json").read_text(encoding="utf-8"))["enums"]
    unify = json.loads((root / "shared/questionnaire-enums.json").read_text(encoding="utf-8"))["enums"]
    languages = json.loads((root / "shared/languages.json").read_text(encoding="utf-8"))
    merged = dict(enums)
    for name, values in unify.items():
        merged.setdefault(name, values)
    lines = [f"// {HEADER}", f"package {PKG[portal]}.questionnaire.data", ""]
    for name, values in merged.items():
        lines.append(f"enum class {name}(val wire: String) {{")
        lines.append(",\n".join(f"    {_kotlin_name(v)}({json.dumps(v)})" for v in values) + ";")
        lines.append("")
        lines.append("    companion object {")
        lines.append(f"        fun fromWire(value: String?): {name}? = entries.firstOrNull {{ it.wire == value }}")
        lines.append("    }")
        lines.append("}")
        lines.append("")
    lines.append("/** Every list above as the shared files spell it, for the parity test. */")
    lines.append("object QuestionnaireVocabulary {")
    lines.append("    val lists: Map<String, List<String>> = linkedMapOf(")
    lines.append(",\n".join(f"        {json.dumps(name)} to {name}.entries.map {{ it.wire }}" for name in merged))
    lines.append("    )")
    lines.append("}")
    lines.append("")
    lines.append("object SharedLanguages {")
    lines.append("    val labels: Map<String, String> = linkedMapOf(")
    lines.append(",\n".join(f"        {json.dumps(l['code'])} to {json.dumps(l['label'], ensure_ascii=False)}" for l in languages["languages"]))
    lines.append("    )")
    lines.append("    val aliases: Map<String, String> = mapOf(")
    lines.append(",\n".join(f"        {json.dumps(a, ensure_ascii=False)} to {json.dumps(c)}" for a, c in languages["aliases"].items()))
    lines.append("    )")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_enums(root: Path) -> bool:
    """Regenerate the enums file; True when it changed."""
    target = _base(root, "main") / ENUMS
    text = enums_text(root, portal_of(root))
    if target.is_file() and target.read_text(encoding="utf-8").replace("\r\n", "\n") == text:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return True


def check(root: Path) -> list[str]:
    problems = []
    target = _base(root, "main") / ENUMS
    if not target.is_file() or target.read_text(encoding="utf-8").replace("\r\n", "\n") != enums_text(root, portal_of(root)):
        problems.append(f"{ENUMS} is out of date with shared/; run scripts/sync_questionnaire.py")
    expected = (root / MANIFEST).read_text(encoding="utf-8").replace("\r\n", "\n") if (root / MANIFEST).is_file() else ""
    if expected != manifest_text(root):
        problems.append(f"{MANIFEST} is out of date; run scripts/sync_questionnaire.py")
    return problems


def sync(root: Path, target: Path | None) -> int:
    """Regenerate the enums and the manifest here; with ``target``, copy every shared file there with
    its package rewritten (and nothing else), remove shared files the source no longer has, and write
    the same manifest there. Returns the number of files copied."""
    write_enums(root)
    text = manifest_text(root)
    (root / MANIFEST).write_text(text, encoding="utf-8", newline="\n")
    if target is None:
        return 0
    source_portal, target_portal = portal_of(root), portal_of(target)
    wanted = set()
    for rel, path in shared_files(root):
        source_set, tree_rel = rel.split("/", 1)
        destination = _base(target, source_set) / tree_rel
        wanted.add(destination.resolve())
        raw = path.read_bytes().decode("utf-8")
        crlf = "\r\n" in raw
        body = raw.replace("\r\n", "\n").replace(PKG[source_portal], PKG[target_portal])
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((body.replace("\n", "\r\n") if crlf else body).encode("utf-8"))
    for rel, path in shared_files(target):
        if path.resolve() not in wanted:
            path.unlink()
    (target / MANIFEST).write_text(text, encoding="utf-8", newline="\n")
    return len(wanted)
