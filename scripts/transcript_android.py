"""The transcript viewer's shared Android trees: generate, digest, copy (DESIGN_2026-10-31 §8.3).

The sibling of ``scripts/questionnaire_android.py``, built the same way and reusing its package
normalisation. The trees below are the same Kotlin in designer-portal and documentation-portal once
the package prefix is normalised (``com.designprototype.workshop`` and ``com.fieldrepository.app``
both read as ``<pkg>``). ``transcript/portal/`` is NOT shared: it is each portal's own adapter (its
HTTP client, who is signed in, how a background pass is asked for), and the shared code reaches the
portal only through it.

Edit the trees in designer-portal, then from this repository's root:

    python scripts/transcript_android.py --to ../documentation-portal     # generate + copy + manifests
    python scripts/transcript_android.py --check                          # verify this repo only

``shared/android-transcript.sha256`` lists every shared file with its normalised digest and is
checked by the shared Android unit test ``transcript/SharedTranscriptTreeTest``.
``transcript/data/TranscriptStrings.kt`` is generated from ``shared/strings/transcript.json`` (T1's
file, never edited here); every other file keeps its own line endings.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from questionnaire_android import PKG, _base, digest, portal_of  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = Path("shared/android-transcript.sha256")
TREES = (("main", "transcript"), ("test", "transcript"), ("androidTest", "transcript"))
STRINGS = "transcript/data/TranscriptStrings.kt"
HEADER = "GENERATED by scripts/transcript_android.py from shared/strings/transcript.json. Do not edit; run the script."


def shared_files(root: Path) -> list[tuple[str, Path]]:
    out: list[tuple[str, Path]] = []
    for source_set, tree in TREES:
        base = _base(root, source_set)
        folder = base / tree
        if not folder.is_dir():
            continue
        for path in sorted(folder.rglob("*.kt")):
            rel = path.relative_to(base).as_posix()
            if rel.startswith("transcript/portal/"):
                continue
            out.append((f"{source_set}/{rel}", path))
    return out


def manifest_text(root: Path) -> str:
    return "".join(f"{digest(path)}  {rel}\n" for rel, path in shared_files(root))


def _kotlin_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("$", "\\$")


def strings_text(root: Path, portal: str) -> str:
    table = json.loads((root / "shared/strings/transcript.json").read_text(encoding="utf-8"))["strings"]
    lines = [f"// {HEADER}", f"package {PKG[portal]}.transcript.data", "", "@Suppress(\"ConstPropertyName\", \"FunctionName\")", "object TranscriptStrings {"]
    for key, value in table.items():
        names = list(dict.fromkeys(re.findall(r"\{(\w+)\}", value)))
        if names:
            params = ", ".join(f"{n}: Any" for n in names)
            body = _kotlin_string(value)
            for n in names:
                body += f".replace(\"{{{n}}}\", {n}.toString())"
            lines.append(f"    fun {key}({params}): String = {body}")
        else:
            lines.append(f"    const val {key} = {_kotlin_string(value)}")
    lines.append("")
    lines.append("    /** Every entry as the table spells it, placeholders and all, for the parity test. */")
    lines.append("    val table: Map<String, String> = linkedMapOf(")
    lines.append(",\n".join(f"        {json.dumps(k)} to {_kotlin_string(v)}" for k, v in table.items()))
    lines.append("    )")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_strings(root: Path) -> bool:
    target = _base(root, "main") / STRINGS
    text = strings_text(root, portal_of(root))
    if target.is_file() and target.read_text(encoding="utf-8").replace("\r\n", "\n") == text:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return True


def check(root: Path) -> list[str]:
    problems = []
    target = _base(root, "main") / STRINGS
    if not target.is_file() or target.read_text(encoding="utf-8").replace("\r\n", "\n") != strings_text(root, portal_of(root)):
        problems.append(f"{STRINGS} is out of date with shared/strings/transcript.json; run scripts/transcript_android.py")
    expected = (root / MANIFEST).read_text(encoding="utf-8").replace("\r\n", "\n") if (root / MANIFEST).is_file() else ""
    if expected != manifest_text(root):
        problems.append(f"{MANIFEST} is out of date; run scripts/transcript_android.py")
    return problems


def sync(root: Path, target: Path | None) -> int:
    write_strings(root)
    text = manifest_text(root)
    (root / MANIFEST).write_text(text, encoding="utf-8", newline="\n")
    if target is None:
        return 0
    source_portal, target_portal = portal_of(root), portal_of(target)
    wanted = set()
    for rel, path in shared_files(root):
        source_set, tree_rel = rel.split("/", 1)
        destination = _base(target, source_set) / tree_rel
        wanted.add(destination.resolve())
        raw = path.read_bytes().decode("utf-8")
        crlf = "\r\n" in raw
        body = raw.replace("\r\n", "\n").replace(PKG[source_portal], PKG[target_portal])
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes((body.replace("\n", "\r\n") if crlf else body).encode("utf-8"))
    for rel, path in shared_files(target):
        if path.resolve() not in wanted:
            path.unlink()
    (target / MANIFEST).write_text(text, encoding="utf-8", newline="\n")
    return len(wanted)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--to", type=Path, help="the other portal's repository root")
    parser.add_argument("--check", action="store_true", help="verify this repository only")
    args = parser.parse_args()
    if args.check:
        problems = check(ROOT)
        print("\n".join(problems) if problems else "transcript Android manifest OK", file=sys.stderr if problems else sys.stdout)
        return 1 if problems else 0
    copied = sync(ROOT, args.to.resolve() if args.to else None)
    if args.to:
        print(f"synced {copied} Android transcript files to {args.to.resolve()}")
        problems = check(args.to.resolve())
        if problems:
            print("\n".join(problems), file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
