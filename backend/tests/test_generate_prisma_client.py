"""scripts/generate_prisma_client.py: the future import, and the types.py / types.pyi split.

The split is what keeps ~1.4 GB of TypedDicts out of every process that imports the client
(see the script's docstring). It edits generated code, so these tests hold it to the shape
prisma-client-py 0.15.0 writes and to refusing any other.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

BACKEND_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND_ROOT / "scripts"))

import generate_prisma_client as gen  # noqa: E402

GENERATED = '''# -*- coding: utf-8 -*-
# code generated by Prisma. DO NOT EDIT.
# pyright: reportUnusedImport=false
# fmt: off

# global imports for type checking
from builtins import bool as _bool
import datetime
from typing import (
    TYPE_CHECKING,
    Any,
    Dict,
    cast,
)
from typing_extensions import TypedDict, Literal


LiteralString = str
# -- template types.py.jinja --
from typing import TypeVar

from . import _types



# TODO: a comment the template carries


SortMode = _types.SortMode
SortOrder = _types.SortOrder

MetricsFormat = _types.MetricsFormat

DatasourceOverride = _types.DatasourceOverride
HttpConfig = _types.HttpConfig


# types that can be serialized to json by our query builder
Serializable = Dict[str, Any]

StringFilter = TypedDict('StringFilter', {'equals': '_str'}, total=False)


class UserCreateInput(TypedDict, total=False):
    email: _str
    createdAt: datetime.datetime
'''


def _package(tmp_path: Path, types_source: str = GENERATED) -> Path:
    package = tmp_path / "fakeprisma"
    package.mkdir()
    (package / "__init__.py").write_text("", encoding="utf-8")
    (package / "_types.py").write_text(
        "from typing import Literal, TypedDict\n"
        "SortMode = Literal['default', 'insensitive']\n"
        "SortOrder = Literal['asc', 'desc']\n"
        "MetricsFormat = Literal['json', 'prometheus']\n"
        "class DatasourceOverride(TypedDict):\n    url: str\n"
        "class HttpConfig(TypedDict, total=False):\n    timeout: int\n",
        encoding="utf-8",
    )
    types_py = package / "types.py"
    types_py.write_text(types_source, encoding="utf-8")
    return types_py


def _import(types_py: Path):
    sys.path.insert(0, str(types_py.parent.parent))
    try:
        for name in [m for m in sys.modules if m == "fakeprisma" or m.startswith("fakeprisma.")]:
            del sys.modules[name]
        spec = importlib.util.find_spec("fakeprisma.types")
        module = importlib.util.module_from_spec(spec)
        sys.modules["fakeprisma.types"] = module
        spec.loader.exec_module(module)
        return module
    finally:
        sys.path.remove(str(types_py.parent.parent))


def test_split_moves_the_declarations_and_keeps_the_runtime_aliases(tmp_path: Path) -> None:
    types_py = _package(tmp_path)
    assert gen.add_future_import(types_py) is True
    full = types_py.read_text(encoding="utf-8")

    assert gen.split_types(types_py) is True

    stub = types_py.with_suffix(".pyi").read_text(encoding="utf-8")
    shim = types_py.read_text(encoding="utf-8")
    assert stub == full
    assert gen.is_runtime_shim(types_py)
    assert "class UserCreateInput" not in shim and "StringFilter" not in shim
    assert shim.splitlines()[1] == "# -*- coding: utf-8 -*-"

    module = _import(types_py)
    from fakeprisma import _types  # type: ignore[import-not-found]

    for name in gen.PREAMBLE_NAMES:
        assert getattr(module, name) is getattr(_types, name)
    # Everything else is a TypedDict at type-check time and a dict at run time.
    assert module.UserCreateInput is dict
    assert module.AnyNameAtAll is dict
    with pytest.raises(AttributeError):
        module.__wrapped__  # noqa: B018 - dunder lookups must still fail


def test_split_is_idempotent_and_check_sees_it(tmp_path: Path) -> None:
    types_py = _package(tmp_path)
    gen.add_future_import(types_py)
    gen.split_types(types_py)
    shim = types_py.read_text(encoding="utf-8")
    assert gen.split_types(types_py) is False
    assert types_py.read_text(encoding="utf-8") == shim
    assert gen.has_future_import(types_py.with_suffix(".pyi"))


def test_split_refuses_a_file_without_the_future_import(tmp_path: Path) -> None:
    types_py = _package(tmp_path)
    with pytest.raises(SystemExit):
        gen.split_types(types_py)


def test_split_refuses_a_shape_it_does_not_know(tmp_path: Path) -> None:
    types_py = _package(tmp_path, GENERATED.replace("# -- template types.py.jinja --\n", ""))
    gen.add_future_import(types_py)
    with pytest.raises(SystemExit):
        gen.split_types(types_py)
    assert not types_py.with_suffix(".pyi").exists()


def test_split_refuses_when_client_py_would_lose_a_name(tmp_path: Path) -> None:
    types_py = _package(tmp_path, GENERATED.replace("HttpConfig = _types.HttpConfig\n", ""))
    gen.add_future_import(types_py)
    with pytest.raises(SystemExit):
        gen.split_types(types_py)
    assert not types_py.with_suffix(".pyi").exists()
