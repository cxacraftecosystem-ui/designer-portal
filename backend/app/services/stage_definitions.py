FROM_REF = "Filled in from the linked record; edits here stay on this report."


def _with_ref_note(details: str) -> str:
    return f"{details} {FROM_REF}" if details else FROM_REF


def f(key: str, label: str, type: FieldType = T, tier: Tier = S, **kw) -> FieldSpec:
    return FieldSpec(key=key, label=label, type=type, tier=tier, **kw)


def fromref(key: str, label: str, type: FieldType = T, tier: Tier = S, **kw) -> FieldSpec:
    kw["details"] = _with_ref_note(str(kw.get("details", "")))
    return FieldSpec(key=key, label=label, type=type, tier=tier, **kw)


def single(
    key: str, name: str, title: str, fields: tuple[FieldSpec, ...], description: str = ""
) -> EntitySpec:
    return EntitySpec(
        key=key,
        name=name,
        cardinality=Cardinality.SINGLETON,
        title=title,
        fields=fields,
        description=description,
    )


def many(
    key: str,
    name: str,
    title: str,
    fields: tuple[FieldSpec, ...],
    label_field: str = "",
    parent: str = "",
    description: str = "",
) -> EntitySpec:
    return EntitySpec(
        key=key,
        name=name,
        cardinality=Cardinality.COLLECTION,
        title=title,
        fields=fields,
        label_field=label_field,
        parent=parent,
        description=description,
    )


def photos(
    key: str = "photos",
    label: str = "Photographs",
    tier: Tier = B,
    caption_label: str = "Photograph caption",
    max_items: int = 0,
    min_items: int = 0,
    help: str = "",
    details: str = "",
) -> tuple[FieldSpec, FieldSpec]:
    return (
        f(
            key,
            label,
            IMGS,
            tier,
            report_role=GALLERY,
            max_items=max_items,
            min_items=min_items,
            help=help,
            details=details,
        ),
        f(f"{key}Caption", caption_label, T, tier, caption_for=key, report_role=CAP),
    )


