#!/usr/bin/env node
/**
 * Bundle the web's 3D model viewer for the handset.
 *
 *     cd frontend && node scripts/build-android-model-viewer.mjs
 *
 * `lib/modelViewerAndroidEntry.ts` (which mounts `lib/modelViewerCore.ts`) and the three.js the web
 * installs are bundled into ONE minified script at
 * `android/app/src/main/assets/model-viewer/viewer.js`, which `DwModelViewer.kt` loads in a WebView.
 * The Android build has no Node toolchain, so the bundle is committed; its first line records the
 * three.js version and a hash of the viewer's sources, and `e2e/model-viewer-unit.spec.ts` fails when
 * either no longer matches — re-run this script and commit the result.
 *
 * esbuild is fetched by npx at the version pinned below rather than added to package.json: nothing
 * else in the web build uses it, and a pinned version keeps the bundle reproducible.
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { modelViewerSourceHash } from "./model-viewer-source-hash.mjs";

const ESBUILD_VERSION = "0.28.2";

const frontend = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(frontend, "..", "android", "app", "src", "main", "assets", "model-viewer", "viewer.js");
mkdirSync(dirname(out), { recursive: true });

const bundled = execFileSync(
  process.platform === "win32" ? "npx.cmd" : "npx",
  [
    "-y",
    `esbuild@${ESBUILD_VERSION}`,
    "lib/modelViewerAndroidEntry.ts",
    "--bundle",
    "--minify",
    "--format=iife",
    "--target=chrome100",
    "--legal-comments=none",
    "--log-level=warning"
  ],
  { cwd: frontend, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, shell: process.platform === "win32" }
);

const threeVersion = JSON.parse(readFileSync(join(frontend, "node_modules", "three", "package.json"), "utf8")).version;
const header =
  `/* dp-model-viewer three@${threeVersion} sources@${modelViewerSourceHash(frontend)} — generated by ` +
  `frontend/scripts/build-android-model-viewer.mjs; three.js is MIT-licensed (c) 2010-2026 three.js authors. */\n`;
writeFileSync(out, header + bundled);
console.log(`wrote ${out} (${(Buffer.byteLength(header + bundled) / 1024).toFixed(0)} KB)`);
